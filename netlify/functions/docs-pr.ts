// POST /api/docs-pr {id, path?}: commit a finished document to a new branch
// in the user's repo and open a pull request (paid plans, GitHub connected).
import type { Handler } from '@netlify/functions';
import { Octokit } from '@octokit/rest';
import { json, errorResponse, parseBody, HttpError } from '../../src/server/http';
import { requireUser, ensureProfile, getPlan, supabaseAdmin } from '../../src/server/supabase';
import { userGithubToken, parseRepo } from '../../src/server/github';
import { DOC_KINDS, DocKind } from '../../src/lib/plans';

export const handler: Handler = async (event) => {
  if (event.httpMethod !== 'POST') return json(405, { error: 'Method not allowed' });
  try {
    const user = await requireUser(event);
    const { id, path: requestedPath } = parseBody(event);
    const profile = await ensureProfile(user);
    const plan = await getPlan(user.id);
    if (!plan.openAsPr && profile.role !== 'admin') {
      throw new HttpError(402, 'Opening docs as a pull request is on the Pro plan.', { code: 'upgrade', plan: 'pro' });
    }

    const db = supabaseAdmin();
    const { data: doc } = await db.from('gs_docs').select('*').eq('id', id).eq('user_id', user.id).maybeSingle();
    if (!doc || doc.status !== 'done') throw new HttpError(404, 'Document not found.');

    const token = await userGithubToken(user.id);
    if (!token) throw new HttpError(400, 'Connect GitHub to open pull requests.', { code: 'github_connect' });

    const path = String(requestedPath || DOC_KINDS[doc.kind as DocKind].file)
      .replace(/^\/+/, '')
      .slice(0, 200);
    if (!/^[\w./-]+\.md$/i.test(path) || path.includes('..')) {
      throw new HttpError(400, 'Use a Markdown file path like docs/ONBOARDING.md.');
    }

    const { owner, repo } = parseRepo(doc.repo_full_name)!;
    const gh = new Octokit({ auth: token });
    const { data: meta } = await gh.repos.get({ owner, repo });
    const base = meta.default_branch;
    const { data: baseRef } = await gh.git.getRef({ owner, repo, ref: `heads/${base}` });

    const branch = `gitsense/${doc.kind}-${new Date().toISOString().slice(0, 10)}-${doc.id.slice(0, 6)}`;
    await gh.git.createRef({ owner, repo, ref: `refs/heads/${branch}`, sha: baseRef.object.sha });

    let existingSha: string | undefined;
    try {
      const { data: existing } = await gh.repos.getContent({ owner, repo, path, ref: branch });
      if (!Array.isArray(existing)) existingSha = existing.sha;
    } catch (err: any) {
      if (err.status !== 404) throw err;
    }

    const label = DOC_KINDS[doc.kind as DocKind].label;
    await gh.repos.createOrUpdateFileContents({
      owner,
      repo,
      path,
      branch,
      sha: existingSha,
      message: `docs: ${existingSha ? 'update' : 'add'} ${label.toLowerCase()} (GitSense)`,
      content: Buffer.from(doc.content + '\n').toString('base64'),
    });

    const { data: pr } = await gh.pulls.create({
      owner,
      repo,
      base,
      head: branch,
      title: `docs: ${label} generated by GitSense`,
      body: `This ${label.toLowerCase()} was generated by [GitSense](https://gitsense.dev) from \`${doc.ref}\`.\n\nPlease review it like any other change: anything marked \`TODO: confirm\` needs a human check.`,
    });

    await db.from('gs_docs').update({ pr_url: pr.html_url }).eq('id', doc.id);
    return json(200, { url: pr.html_url });
  } catch (err: any) {
    if (!(err instanceof HttpError) && (err?.status === 403 || err?.status === 404)) {
      return json(403, { error: 'GitHub would not let us push to this repo. Check that your account can write to it.' });
    }
    return errorResponse(err);
  }
};
